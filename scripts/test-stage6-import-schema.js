"use strict";
const assert = require("assert");
const fs = require("fs");
const path = require("path");
const { createMemoryStorage, createTab, loadScript } = require("./support/copdoc-vm-harness.js");
const fixture = JSON.parse(fs.readFileSync(path.join(__dirname, "fixtures/stage6-bookin-v1.12-schema5.json"), "utf8"));
const clone = value => JSON.parse(JSON.stringify(value));
const storage = createMemoryStorage();
const tab = createTab(storage);
loadScript(tab, "functions/import-schema.js");
const api = tab.COPDoc.importSchema;
let result = api.decode(fixture);
assert.ok(result.ok, result.error);
assert.ok(result.findings.some(row => row.code === "CARD_RENDERER_REQUIRED"), "decode retains cards but requires actual contract before commit");
loadScript(tab, "functions/baseball-card-contract.js");
result = api.decode(fixture);
assert.ok(result.ok, result.error);
assert.strictEqual(result.schemaVersion, 5);
assert.strictEqual(result.records[0].sourceExtension.preserveThis, "unknown extension");
assert.strictEqual(result.records[0].formState.future_field.value, "preserve custom field");
assert.strictEqual(result.records[0].formState.no_medical_issues.checked, false, "explicit false answers survive");
assert.strictEqual(result.records[0].importSource.metadata.exportExtension.origin, "synthetic fixture");
assert.strictEqual(result.records[0].baseballCard.layout.cardWidthPx, 1200);
assert.strictEqual(result.records[0].baseballCard.photoAdjustments.positionX, 31);
assert.strictEqual(result.records[0].baseballCard.content.narrative, "Manually edited synthetic narrative.");
assert.strictEqual(result.records[0].baseballCard.criminalHistory[0].convictionDate, "2024-02-02", "saved history order is preserved");
assert.strictEqual(result.records[0].baseballCard.criminalHistory[0].sourceTag, "preserve history extension");
assert.strictEqual(result.records[0].baseballCard.layout.customLayoutExtension, "retain");
assert.ok(!result.records[0].encounterId && !result.records[0].outcome, "display Encounter labels do not mint canonical joins/outcomes");
assert.deepStrictEqual(storage.dump(), {}, "decoder does not persist");
assert.deepStrictEqual(api.decode(fixture), api.decode(JSON.stringify(fixture)), "object and JSON inputs produce identical data");
for (let version = 1; version <= 5; version++) {
  const data = clone(fixture); data.schemaVersion = version;
  if (version < 5) delete data.records[0].baseballCard;
  assert.ok(api.decode(data).ok, "legacy schema " + version);
}
function rejected(change, pattern) {
  const data = clone(fixture); change(data);
  const answer = api.decode(data);
  assert.strictEqual(answer.ok, false, JSON.stringify(answer));
  if (pattern) assert.match(answer.error, pattern);
}
rejected(data => data.schemaVersion = 6, /unsupported/i);
rejected(data => delete data.schemaVersion, /legacy/i);
const legacy = clone(fixture); delete legacy.schemaVersion;
assert.ok(api.decode(legacy, { allowUnversionedLegacy: true }).ok);
rejected(data => data.records = {}, /list/i);
rejected(data => data.recordCount = 2, /recordCount/i);
rejected(data => { data.records.push(clone(data.records[0])); data.recordCount = 2; }, /duplicate/i);
rejected(data => data.records[0].bookingId = "other", /contradictory/i);
rejected(data => { data.records[0].subjectId = "one"; data.records[0].encounterSubjectId = "two"; }, /contradictory/i);
rejected(data => data.records[0].formState = [], /formState/i);
rejected(data => data.records[0].formState.no_medical_issues.checked = "false", /checked/i);
rejected(data => data.records[0].formState.future_field.value = "X".repeat(100001), /long/i);
rejected(data => data.records[0].baseballCard.photoDataUrl = "https://example.invalid/photo", /photo/i);
rejected(data => data.records[0].baseballCard.photoDataUrl = "data:image/svg+xml;base64,PHN2Zz4=", /photo/i);
rejected(data => data.records[0].baseballCard.criminalHistory = {}, /history/i);
rejected(data => data.records[0].revision = -1, /revision/i);
rejected(data => data.records[0].updatedAt = "not-a-date", /updatedAt/i);
assert.ok(!api.decode('{"format":"alien-book-in-records","schemaVersion":5,"records":[],"__proto__":{}}').ok);
const nic = clone(fixture); nic.records[0].caseType = "NIC";
const reviewed = api.decode(nic);
assert.ok(reviewed.ok);
assert.ok(reviewed.findings.some(row => row.code === "CUSTODY_REVIEW"));
assert.ok(!reviewed.records[0].outcome, "NIC never becomes an invented Encounter outcome");
console.log("ok Stage 6 shared schema decoder: schema1–5, lossless extensions/cards, explicit custody review, malformed/future imports rejected");

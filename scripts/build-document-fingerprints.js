"use strict";
const fs = require("fs"), path = require("path"), crypto = require("crypto"), vm = require("vm");
const root = path.resolve(__dirname, "..");
const { dependencies } = require("./support/module-dependencies.js");
function build() {
  const context = vm.createContext({});
  vm.runInContext(fs.readFileSync(path.join(root, "functions/document-registry.js"), "utf8"), context);
  const fingerprints = {};
  context.COPDoc.documents.registry.all().forEach(entry => {
    fingerprints[entry.documentType] = {};
    // A renderer's extracted prerequisites are part of the same implementation.
    const sources = new Set(entry.template.sourceFiles.flatMap(file => [file, ...dependencies(file)]));
    Array.from(sources).sort().forEach(file => {
      if (!/^(?:functions|assets|style|vendor)\/[A-Za-z0-9_./-]+$|^[A-Za-z0-9_-]+\.html$/.test(file) || file.includes("..")) throw new Error("Invalid template source " + file);
      fingerprints[entry.documentType][file] = crypto.createHash("sha256").update(fs.readFileSync(path.join(root, file))).digest("hex");
    });
  });
  return "/** Generated by scripts/build-document-fingerprints.js. Do not edit hashes by hand. */\n(function (global) {\n  var app = global.COPDoc = global.COPDoc || {};\n  var docs = app.documents = app.documents || {};\n  docs.templateFingerprints = " + JSON.stringify(fingerprints, null, 2) + ";\n})(typeof window !== \"undefined\" ? window : globalThis);\n";
}
if (require.main === module) {
  const expected = build(), output = path.join(root, "functions/document-fingerprints.js");
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(output) || fs.readFileSync(output, "utf8") !== expected) throw new Error("Document template sources changed. Review field dependencies and output fixtures, then run node scripts/build-document-fingerprints.js.");
    console.log("Document source fingerprints match all registered renderer/template files.");
  } else { fs.writeFileSync(output, expected); console.log("Updated document source fingerprints."); }
}
module.exports = { build };
